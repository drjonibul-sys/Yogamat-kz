'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const dir=path.join(__dirname,'../dist');
const html=fs.readFileSync(path.join(dir,'index.html'),'utf8');
const script=fs.readFileSync(path.join(dir,'updates.js'),'utf8');
const sw=fs.readFileSync(path.join(dir,'sw.js'),'utf8');
const meta=JSON.parse(fs.readFileSync(path.join(dir,'app-update.json'),'utf8'));
assert.match(html,/<script src="updates.js"><\/script>/);
assert.equal(meta.app,'yoga-practice-pwa');
assert.match(meta.version,/^[a-f0-9]{16}$/);
assert.ok(sw.includes(`const VERSION = '${meta.version}'`));
assert.match(sw,/fetch\(new Request\(request, \{cache:'no-store'\}\)\)/);
assert.match(sw,/event\.data\?\.type === 'SKIP_WAITING'/);
assert.match(script,/settings\.source = normalize/);
assert.match(script,/settings\.auto=event\.target\.checked/);
assert.match(script,/if\(!confirm\('Установить версию /);
assert.match(script,/registration\.waiting\.postMessage\(\{type:'SKIP_WAITING'\}\)/);
assert.match(script,/createBackup\('pre-update'\)/);
assert.doesNotMatch(script,/localStorage\.clear\(|indexedDB\.deleteDatabase\(|caches\.delete\(/);
new vm.Script(script);
console.log('PASS: update manifest, cache bypass, settings, confirmation, backup and no data deletion');
